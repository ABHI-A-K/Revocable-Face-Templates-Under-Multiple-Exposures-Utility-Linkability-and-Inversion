"""Regenerate shared headline metrics and audit the editorial structure."""
from pathlib import Path
import json,re
import pandas as pd
P=Path(__file__).resolve().parent
c=pd.read_csv(P/'data/encoder_extension/CFP_encoder_comparison.csv')
o=pd.read_csv(P/'data/identity_bootstrap_intervals.csv')
def ran(x):
 assert len(x)==3 and x.notna().all()
 return f'{100*x.min():.2f}--{100*x.max():.2f}'+r'\%'
v={}
for bits,size in [(128,'Small'),(512,'Large')]:
 for field,encoder in [('mbf','Mbf'),('r50','Rnet')]:
  for metric,label in [('tar','Tar'),('asr','Asr')]:v[encoder+size+label]=ran(c.loc[c.bits==bits,field+'_'+metric])
v['LfwBaselineAsr']=ran(o.query('dataset=="LFW" and bits==128 and K==10 and attack=="calibrated" and metric=="fresh_asr"')['mean'])
(P/'metrics.tex').write_text('% Generated by editorial_metrics.py from included CSV evidence.\n'+'\n'.join('\\newcommand{\\'+k+'}{'+val+'}' for k,val in v.items())+'\n')
texts=[p.read_text() for p in (P/'sections').glob('*.tex')]
joined='\n'.join(texts)
tables=re.findall(r'\\begin\{table\*?\}.*?\\end\{table\*?\}',joined,re.S)
figures=re.findall(r'\\begin\{figure\*?\}.*?\\end\{figure\*?\}',joined,re.S)
tables.append((P/'sections/notation.tex').read_text())
assert len(tables)==16 and len(figures)==13
assert all(re.search(r'\\caption\{[^}]+\}',t) and '\\tabnote{' in t for t in tables)
assert all('\\caption{' in f and '\\fignote{' in f for f in figures)
assert len(re.findall(r'\\section\{',joined))==7
# Main numerical comparison table must agree with its source for all six rows.
t=(P/'sections/encoder_cfp_table.tex').read_text()
for r in c.itertuples():
 label=r.method.replace('PCA_GUIDED_RO','PCA-guided RO')
 expected=f'{r.bits} & {label} & {100*r.mbf_tar:.2f} / {100*r.mbf_far:.3f} & {100*r.r50_tar:.2f} / {100*r.r50_far:.3f} & {100*r.mbf_asr:.2f} & {100*r.r50_asr:.2f} & {100*r.delta:.2f} [{100*r.delta_low:.2f}, {100*r.delta_high:.2f}]'
 assert expected in t
s=pd.read_csv(P/'data/encoder_extension/lfw/summary.csv').query('evaluation=="matcher_only"')
t=(P/'sections/encoder_lfw_table.tex').read_text()
for method,label in [('RAW','Raw'),('RO','RO'),('SRHT','SRHT'),('PCA_GUIDED_RO','PCA-guided RO')]:
 a=s[(s.encoder=='MobileFaceNet')&(s.method==method)].iloc[0];b=s[(s.encoder=='ResNet50_ArcFace')&(s.method==method)].iloc[0]
 assert f'{label} & {100*a.tar:.2f} & {100*b.tar:.2f} & {100*a.far:.3f} & {100*b.far:.3f}' in t
status={'status':'PASS','revision':'14 October 2026','sections':7,'tables_with_captions_and_notes':len(tables),'figures_with_captions_and_notes':len(figures),'cfp_encoder_rows_checked':6,'lfw_encoder_rows_checked':4,'shared_headline_metrics':v,'experimental_data_changed':False}
(P/'data/encoder_extension/editorial_validation.json').write_text(json.dumps(status,indent=2))
print('PASS: shared numerical ranges, 10 encoder-comparison rows, 7 sections, 16 table notes, 13 figure notes')
